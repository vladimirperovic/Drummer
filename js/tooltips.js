export function applyTooltips(root = document) {
  for (const [selector, tip] of TIPS) {
    for (const el of root.querySelectorAll(selector)) {
      if (el.title) continue;
      const text = typeof tip === 'function' ? tip(el) : tip;
      if (text) el.title = text;
    }
  }
}

// Novi elementi dobijaju opis u sledećem kadru, jednom za ceo niz izmena.
export function setupTooltips() {
  applyTooltips();
  let queued = false;
  new MutationObserver(records => {
    if (queued || !records.some(r => [...r.addedNodes].some(n => n.nodeType === 1 && !(n instanceof SVGElement)))) return;
    queued = true;
    requestAnimationFrame(() => { queued = false; applyTooltips(); });
  }).observe(document.body, { childList: true, subtree: true });
}
